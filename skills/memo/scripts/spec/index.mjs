// Generated catalogs. INDEX.md lists top-level docs/ files and the first TASKS_IN_INDEX tasks; tasks/INDEX.md lists every task.
// Both are rewritten by spec_edit in the same save and are never edited by hand.
import path from "node:path";
import { fail } from "./io.mjs";
import { Documents, Frontmatter } from "./metadata.mjs";

export class ProjectIndex {
  static TASKS_IN_INDEX = 5;
  // Injected beside MEMORY.md; together they stay below the hosts' hook limits.
  static BYTES = 1500;
  static NOTE = "<!-- Generated by Gei Spec from docs/ and tasks/ frontmatter. Do not edit. -->";

  static scope(docPath) { return Documents.split(docPath).scope; }
  static indexPath(scope) { return `${scope}INDEX.md`; }
  static tasksIndexPath(scope) { return `${scope}tasks/INDEX.md`; }
  static body(content) { return String(content || "").replace(/<!--[\s\S]*?-->/gu, "").trim(); }

  static text(value) {
    let text = String(value).replace(/\\/gu, "\\\\");
    while (text.includes("<!--")) text = text.replaceAll("<!--", "<!-");
    return text.replace(/[\[\]]/gu, "").replace(/[\s\u0085\u2028\u2029]+/gu, " ").trim();
  }

  // First ATX H1 outside fenced code and HTML comments; the file stem otherwise.
  static title(docPath, content) {
    let fence = null, comment = false;
    for (const raw of Frontmatter.split(content).body.split("\n")) {
      const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/u.exec(raw);
      if (fence) {
        if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length && !marker[2].trim()) fence = null;
        continue;
      }
      if (comment) { comment = !raw.includes("-->"); continue; }
      const at = raw.indexOf("<!--");
      if (at >= 0) { comment = raw.indexOf("-->", at + 4) < 0; continue; }
      if (marker) { fence = marker[1]; continue; }
      const heading = /^#\s+(.+?)(?:\s+#+)?$/u.exec(raw.trim());
      if (heading) return this.text(heading[1]) || "document";
    }
    return this.text(path.posix.basename(docPath, ".md")) || "document";
  }

  static catalog(files, scope) {
    const docs = [], tasks = [];
    for (const [name, content] of Object.entries(files)) {
      if (!name.startsWith(scope) || typeof content !== "string") continue;
      const kind = Documents.kind(name);
      // A doc in a subdirectory of docs/ is reached through links from a top-level doc.
      if ((kind !== "doc" && kind !== "task") || (kind === "doc" && Documents.split(name).rest.split("/").length > 2)) continue;
      if (Frontmatter.problems(name, content).length) continue;
      const { values } = Frontmatter.scalars(content);
      const entry = { path: name, title: this.title(name, content), description: this.text(values.description), status: values.status };
      (kind === "task" ? tasks : docs).push(entry);
    }
    const byPath = (a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0;
    const rank = status => ["doing", "blocked", "todo"].indexOf(status);
    docs.sort(byPath);
    tasks.sort((a, b) => rank(a.status) - rank(b.status) || byPath(a, b));
    return { docs, tasks };
  }

  static link(indexPath, entry) {
    const relative = path.posix.relative(path.posix.dirname(indexPath), entry.path);
    const href = /[()\s]/u.test(relative) ? `<${relative}>` : relative;
    return `- [${entry.title}](${href}): ${entry.description}${entry.status ? ` (${entry.status})` : ""}`;
  }

  static build(scope, { docs, tasks }) {
    const indexPath = this.indexPath(scope);
    const lines = [this.NOTE];
    if (docs.length) lines.push("", "## docs", "", ...docs.map(entry => this.link(indexPath, entry)));
    if (tasks.length) {
      lines.push("", "## tasks", "", ...tasks.slice(0, this.TASKS_IN_INDEX).map(entry => this.link(indexPath, entry)));
      if (tasks.length > this.TASKS_IN_INDEX) lines.push(`更多任务 ${tasks.length - this.TASKS_IN_INDEX} 个，见 [tasks/INDEX.md](tasks/INDEX.md)`);
    }
    return docs.length || tasks.length ? lines.join("\n") + "\n" : null;
  }

  static buildTasks(scope, { tasks }) {
    if (!tasks.length) return null;
    const indexPath = this.tasksIndexPath(scope);
    return [this.NOTE, "", ...tasks.map(entry => this.link(indexPath, entry))].join("\n") + "\n";
  }

  static scopesTouched(before, after) {
    const scopes = new Set();
    for (const name of new Set([...Object.keys(before), ...Object.keys(after)])) {
      if (before[name] !== after[name]) scopes.add(this.scope(name));
    }
    return [...scopes].sort();
  }

  static apply(files, before, scopes) {
    for (const scope of scopes) {
      const catalog = this.catalog(files, scope);
      for (const [name, content] of [[this.indexPath(scope), this.build(scope, catalog)], [this.tasksIndexPath(scope), this.buildTasks(scope, catalog)]]) {
        if (content === null) delete files[name]; else files[name] = content;
      }
      const size = Buffer.byteLength(this.body(files[this.indexPath(scope)]), "utf8");
      if (size > this.BYTES && size > Buffer.byteLength(this.body(before[this.indexPath(scope)]), "utf8")) {
        fail("INDEX_FULL", `${this.indexPath(scope)} would be ${size} bytes; the limit is ${this.BYTES}. Shorten doc descriptions, merge docs, or finish tasks in this batch.`, { applied: false, bytes: size, limit: this.BYTES });
      }
    }
  }
}
